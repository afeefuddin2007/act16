void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(const QuizApp());
}

class QuizApp extends StatelessWidget {
  const QuizApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'ICA16 Quiz',
      theme: ThemeData(colorSchemeSeed: Colors.indigo, useMaterial3: true),
      home: StreamBuilder<User?>(
        stream: FirebaseAuth.instance.authStateChanges(),
        builder: (context, snap) {
          if (snap.connectionState == ConnectionState.waiting) {
            return const Scaffold(body: Center(child: CircularProgressIndicator()));
          }
          final user = snap.data;
          if (user == null) return const SignInPage();
          // Keyed by UID so a user switch discards the old round entirely.
          return QuizPage(key: ValueKey(user.uid), uid: user.uid);
        },
      ),
    );
  }
}

class SignInPage extends StatefulWidget {
  const SignInPage({super.key});

  @override
  State<SignInPage> createState() => _SignInPageState();
}

class _SignInPageState extends State<SignInPage> {
  final _email = TextEditingController();
  final _password = TextEditingController();
  String? _error;
  bool _busy = false;

  @override
  void dispose() {
    _email.dispose();
    _password.dispose();
    super.dispose();
  }

  Future<void> _signIn() async {
    setState(() {
      _busy = true;
      _error = null;
    });
    try {
      await FirebaseAuth.instance.signInWithEmailAndPassword(
        email: _email.text.trim(),
        password: _password.text,
      );
    } on FirebaseAuthException catch (e) {
      if (mounted) setState(() => _error = 'Sign-in failed: ${e.code}');
    } finally {
      if (mounted) setState(() => _busy = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(title: const Text('Sign in')),
      body: Padding(
        padding: const EdgeInsets.all(24),
        child: Column(
          children: [
            TextField(
              controller: _email,
              decoration: const InputDecoration(labelText: 'Email'),
              keyboardType: TextInputType.emailAddress,
            ),
            TextField(
              controller: _password,
              decoration: const InputDecoration(labelText: 'Password'),
              obscureText: true,
            ),
            const SizedBox(height: 16),
            FilledButton(
              onPressed: _busy ? null : _signIn,
              child: const Text('Sign in'),
            ),
            if (_error != null)
              Padding(
                padding: const EdgeInsets.only(top: 12),
                child: Text(_error!, style: const TextStyle(color: Colors.red)),
              ),
          ],
        ),
      ),
    );
  }
}

enum Phase {
  loading,
  playing,
  finished,
  submitting,
  verifying,
  verified,
  saveUnknown,
  verificationUnavailable,
  error,
}

class QuizPage extends StatefulWidget {
  const QuizPage({super.key, required this.uid});
  final String uid;

  @override
  State<QuizPage> createState() => _QuizPageState();
}

class _QuizPageState extends State<QuizPage> {
  final _repo = AttemptRepository();
  List<QuizQuestion> _questions = [];
  List<String?> _answers = [];
  int _index = 0;
  Phase _phase = Phase.loading;
  String? _message;
  late String _roundId;
  int _submittedScore = 0;
  SaveFault _fault = SaveFault.none; // DEV ONLY

  @override
  void initState() {
    super.initState();
    _startRound();
  }

  bool get _unresolved => const {
        Phase.submitting,
        Phase.verifying,
        Phase.saveUnknown,
        Phase.verificationUnavailable,
      }.contains(_phase);

  int get _score {
    var s = 0;
    for (var i = 0; i < _questions.length; i++) {
      if (_answers[i] == _questions[i].correct) s++;
    }
    return s;
  }

  void _setPhase(Phase p, String? msg) {
    if (!mounted) return;
    setState(() {
      _phase = p;
      _message = msg;
    });
  }

  Future<void> _startRound() async {
    _roundId = _repo.newRoundId(widget.uid);
    setState(() {
      _phase = Phase.loading;
      _message = null;
      _index = 0;
      _questions = [];
      _answers = [];
    });
    try {
      final qs = await fetchQuiz();
      if (!mounted) return;
      setState(() {
        _questions = qs;
        _answers = List<String?>.filled(qs.length, null);
        _phase = Phase.playing;
      });
    } on QuizFetchException catch (e) {
      _setPhase(Phase.error, e.message);
    }
  }

  void _answer(String choice) {
    if (_phase != Phase.playing || _answers[_index] != null) return;
    setState(() => _answers[_index] = choice);
  }

  void _next() {
    if (_answers[_index] == null) return;
    setState(() {
      if (_index < _questions.length - 1) {
        _index++;
      } else {
        _phase = Phase.finished;
      }
    });
  }

  Future<void> _submit() async {
    if (_phase != Phase.finished) return;
    _submittedScore = _score;
    _setPhase(Phase.submitting, null);
    try {
      await _repo.saveOnce(
        uid: widget.uid,
        roundId: _roundId,
        correctCount: _submittedScore,
        fault: _fault,
      );
    } on TimeoutException {
      _setPhase(Phase.saveUnknown,
          'Acknowledgement lost. The server may have saved this round. Check the server before retrying.');
      return;
    } on AttemptException catch (e) {
      // Settled failures can be retried with the same ID; unknown cannot.
      _setPhase(
        e.kind == SaveFailure.unknown ? Phase.saveUnknown : Phase.finished,
        e.message,
      );
      return;
    }
    await _checkServer();
  }

  Future<void> _checkServer() async {
    _setPhase(Phase.verifying, null);
    try {
      await _repo.verify(
        uid: widget.uid,
        roundId: _roundId,
        correctCount: _submittedScore,
      );
      _setPhase(Phase.verified, null);
    } on AttemptException catch (e) {
      switch (e.kind) {
        case SaveFailure.notFound:
          // Server confirmed absence: the same ID may be submitted again.
          _setPhase(Phase.finished,
              'Server has no record for this round yet. You may submit again with the same round ID.');
        case SaveFailure.mismatch:
          _setPhase(Phase.error,
              'Server data for this round ID differs. Start a new round.');
        default:
          _setPhase(Phase.saveUnknown, e.message);
      }
    } on FirebaseException catch (e) {
      // The save may have succeeded; only verification is unavailable.
      _setPhase(Phase.verificationUnavailable,
          'Verification unavailable (${e.code}). This is not a save failure. Check again when online.');
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: const Text('General Knowledge (Class A)'),
        actions: [
          IconButton(
            tooltip: 'Sign out',
            icon: const Icon(Icons.logout),
            onPressed: _unresolved
                ? null
                : () => FirebaseAuth.instance.signOut(),
          ),
        ],
      ),
      body: Padding(padding: const EdgeInsets.all(16), child: _body()),
    );
  }

  Widget _body() {
    switch (_phase) {
      case Phase.loading:
        return const Center(child: CircularProgressIndicator());
      case Phase.error:
        return Center(
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              Text(_message ?? 'Error', textAlign: TextAlign.center),
              const SizedBox(height: 12),
              FilledButton(onPressed: _startRound, child: const Text('Retry')),
            ],
          ),
        );
      case Phase.playing:
        return _questionView();
      default:
        return _resultView();
    }
  }

  Widget _questionView() {
    final q = _questions[_index];
    final chosen = _answers[_index];
    final answered = chosen != null;
    return ListView(
      children: [
        LinearProgressIndicator(value: _index / _questions.length),
        const SizedBox(height: 8),
        Text('Question ${_index + 1} of ${_questions.length}'),
        const SizedBox(height: 12),
        Text(q.text, style: Theme.of(context).textTheme.titleMedium),
        const SizedBox(height: 12),
        for (final c in q.choices)
          Card(
            child: ListTile(
              title: Text(c),
              leading: Icon(
                answered && c == q.correct
                    ? Icons.check_circle
                    : answered && c == chosen
                        ? Icons.cancel
                        : Icons.radio_button_unchecked,
                color: answered && c == q.correct
                    ? Colors.green
                    : answered && c == chosen
                        ? Colors.red
                        : null,
              ),
              onTap: answered ? null : () => _answer(c),
            ),
          ),
        const SizedBox(height: 12),
        if (answered)
          Text(
            chosen == q.correct
                ? 'Correct!'
                : 'Incorrect. The answer is: ${q.correct}',
            style: TextStyle(
              fontWeight: FontWeight.bold,
              color: chosen == q.correct ? Colors.green : Colors.red,
            ),
          ),
        const SizedBox(height: 12),
        FilledButton(
          onPressed: answered ? _next : null,
          child: Text(_index < _questions.length - 1 ? 'Next' : 'Finish'),
        ),
      ],
    );
  }

  Widget _resultView() {
    final suffix = _roundId.length >= 6
        ? _roundId.substring(_roundId.length - 6)
        : _roundId;
    final statusText = switch (_phase) {
      Phase.finished => _message ?? 'Ready to submit to the cloud.',
      Phase.submitting => 'Saving to cloud… (buttons disabled)',
      Phase.verifying => 'Confirming on server…',
      Phase.verified => 'Cloud verified ✔ (round ...$suffix)',
      Phase.saveUnknown => _message ?? 'Save status unknown.',
      Phase.verificationUnavailable => _message ?? 'Verification unavailable.',
      Phase.error => _message ?? 'Error.',
      _ => '',
    };

    return ListView(
      children: [
        Text('Score: ${_score} / ${_questions.length}',
            style: Theme.of(context).textTheme.headlineSmall),
        const SizedBox(height: 8),
        Text(statusText),
        const SizedBox(height: 12),
        for (var i = 0; i < _questions.length; i++)
          ListTile(
            leading: Icon(
              _answers[i] == _questions[i].correct
                  ? Icons.check_circle
                  : Icons.cancel,
              color: _answers[i] == _questions[i].correct
                  ? Colors.green
                  : Colors.red,
            ),
            title: Text('${i + 1}. ${_questions[i].text}'),
            subtitle: Text(
                'Your answer: ${_answers[i] ?? '-'}\nCorrect: ${_questions[i].correct}'),
          ),
        const Divider(),
        if (_phase == Phase.finished)
          SwitchListTile(
            title: const Text('DEV ONLY: fault injection'),
            subtitle: DropdownButton<SaveFault>(
              value: _fault,
              items: [
                for (final f in SaveFault.values)
                  DropdownMenuItem(value: f, child: Text(f.name)),
              ],
              onChanged: (v) => setState(() => _fault = v ?? SaveFault.none),
            ),
            value: _fault != SaveFault.none,
            onChanged: (on) =>
                setState(() => _fault = on ? SaveFault.lostAck : SaveFault.none),
          ),
        FilledButton(
          onPressed: _phase == Phase.finished ? _submit : null,
          child: const Text('Submit to cloud'),
        ),
        const SizedBox(height: 8),
        OutlinedButton(
          onPressed: _phase == Phase.saveUnknown ||
                  _phase == Phase.verificationUnavailable
              ? _checkServer
              : null,
          child: const Text('Check server (same round ID)'),
        ),
        const SizedBox(height: 8),
        OutlinedButton(
          // Replay only after the round is settled; never while unresolved.
          onPressed: (!_unresolved && _phase != Phase.loading) ? _startRound : null,
          child: const Text('Replay (new round ID)'),
        ),
      ],
    );
  }
}
